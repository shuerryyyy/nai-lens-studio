"""Generate and check the exact public files used offline. Run from any directory."""
import argparse
import base64
import hashlib
import json
import re
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


class ShellLinks(HTMLParser):
    def __init__(self):
        super().__init__()
        self.urls = set()

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "script" and "src" in attrs:
            self.urls.add(attrs["src"])
        if tag == "link" and attrs.get("rel") in {"stylesheet", "icon", "manifest", "apple-touch-icon"}:
            self.urls.add(attrs["href"])


def shell_file(url):
    parts = urlsplit(url)
    path = Path(parts.path)
    if parts.scheme or parts.netloc or parts.fragment or path.is_absolute() or ".." in path.parts:
        raise ValueError(f"Expected a local shell asset: {url}")
    if path.as_posix() not in {"index.html", "manifest.webmanifest"} and path.parts[:1] != ("assets",):
        raise ValueError(f"Unexpected shell path: {url}")
    return ROOT / path


def generate():
    links = ShellLinks()
    links.feed((ROOT / "index.html").read_text(encoding="utf-8"))
    urls = links.urls | {"./index.html"}
    manifest = json.loads((ROOT / "manifest.webmanifest").read_text(encoding="utf-8"))
    urls.update(icon["src"] for icon in manifest["icons"])
    for url in sorted(urls):
        css = shell_file(url)
        if css.suffix == ".css":
            for _, ref in re.findall(r"""url\(\s*(['"]?)([^)'"]+)\1\s*\)""", css.read_text(encoding="utf-8")):
                if not ref.startswith("data:"):
                    dependency = "./" + (css.parent.relative_to(ROOT) / ref).as_posix()
                    shell_file(dependency)
                    urls.add(dependency)
    hashes = {}
    for url in sorted(urls):
        digest = hashlib.sha256(shell_file(url).read_bytes()).digest()
        hashes[url] = "sha256-" + base64.b64encode(digest).decode("ascii")
    entries = json.dumps(hashes, indent=2)
    version = hashlib.sha256(entries.encode()).hexdigest()[:24]
    return f'// Generated by tools/pwa-shell.py\nconst SHELL_VERSION = "{version}";\nconst SHELL_FILES = {entries};\n'


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "pwa-shell.js"
    expected = generate().encode()
    if args.check:
        if not output.exists() or output.read_bytes() != expected:
            parser.exit(1, "Offline shell is stale. Run python3 tools/pwa-shell.py\n")
    else:
        output.write_bytes(expected)
